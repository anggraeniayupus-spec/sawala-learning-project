// Contoh variabel dan tipe data dasar di JavaScript

// const = nilai yang tidak bisa diubah (konstan)
const namaProduk = "Laptop Gaming";

// let = nilai yang bisa diubah-ubah
let harga = 12000000;
let stok = 5;

// Ubah harga & stok (misalnya ada diskon dan ada yang beli)
harga = 11000000; // Ceritanya lagi diskon
stok = stok - 1;  // Terus ada yang beli 1

console.log("Nama Produk:", namaProduk);
console.log("Harga Baru:", harga);
console.log("Sisa Stok:", stok);
